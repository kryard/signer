function makeCreateKeyBody(name: string) {
  return {
    type: "ACTIVITY_TYPE_CREATE_PRIVATE_KEYS_V2",
    organizationId,
    timestampMs: String(Date.now()),
    parameters: { name, curve: "CURVE_SECP256K1", addressFormats: [] },
  };
}

function makeSignTxBody(signWith: string, unsignedTransaction: string, extra: Record<string, unknown> = {}) {
  return {
    type: "ACTIVITY_TYPE_SIGN_TRANSACTION_V2",
    organizationId,
    timestampMs: String(Date.now()),
    parameters: {
      signWith,
      unsignedTransaction,
      type: "TRANSACTION_TYPE_ETHEREUM",
      ...extra,
    },
  };
}

async function submitCreateKey(name = `signtx-key-${Date.now()}`) {
  const body = makeCreateKeyBody(name);
  const init = await stampedRequest(stamper, body);
  const res = await app.request("/public/v1/submit/create_private_keys", init);
  expect(res.status).toBe(200);
  const json = (await res.json()) as {
    activity: {
      status: string;
      result: {
        createPrivateKeysResult: {
          privateKeyIds: string[];
          addresses: { address: string }[];
        };
      };
    };
  };
  expect(json.activity.status).toBe("ACTIVITY_STATUS_COMPLETED");
  const privateKeyId = json.activity.result.createPrivateKeysResult.privateKeyIds[0];
  const address = json.activity.result.createPrivateKeysResult.addresses[0].address;
  return { privateKeyId, address };
}

async function submitSignTx(
  signWith: string,
  unsignedTransaction: string,
  extra: Record<string, unknown> = {},
) {
  const body = makeSignTxBody(signWith, unsignedTransaction, extra);
  const init = await stampedRequest(stamper, body);
  return app.request("/public/v1/submit/sign_transaction", init);
}

/**
 * Derive the Ethereum address from a compressed secp256k1 public key hex.
 * Ethereum address = keccak256(uncompressed_pubkey[1:])[12:]
 */
function addressFromCompressedPubkey(compressedPubHex: string): string {
  const compressedPub = hexToBytes(compressedPubHex);
  const point = secp256k1.ProjectivePoint.fromHex(compressedPub);
  const uncompressed = point.toRawBytes(false); // 65 bytes: 0x04 || x || y
  const pubBody = uncompressed.slice(1); // 64 bytes: x || y
  const hash = keccak_256(pubBody);
  const addrBytes = hash.slice(12); // last 20 bytes
  return "0x" + bytesToHex(addrBytes);
}

/**
 * Derive the Ethereum address from the signer receipt public key.
 * Used for legacy and secondary assertions.
 */
function addressFromSignerReceipt(signerReceiptPublicKey: string): string {
  return addressFromCompressedPubkey(signerReceiptPublicKey);
}

// ---------------------------------------------------------------------------
// Minimal RLP decoder — sufficient to extract last N big-integer items from
// a top-level RLP list (used for EIP-1559 signed tx parsing).
// ---------------------------------------------------------------------------

/** Decode the length and payload offset of a single RLP item starting at `buf[offset]`.
 *  Returns [contentStart, contentLength, totalItemLength]. */
function rlpItemBounds(buf: Uint8Array, offset: number): [number, number, number] {
  const prefix = buf[offset];
  if (prefix <= 0x7f) {
    // Single-byte string (the byte itself is the value).
    return [offset, 1, 1];
  }
  if (prefix <= 0xb7) {
    // Short string: 0x80..0xb7 — next (prefix - 0x80) bytes are content.
    const len = prefix - 0x80;
    return [offset + 1, len, 1 + len];
  }
  if (prefix <= 0xbf) {
    // Long string: 0xb8..0xbf — next (prefix - 0xb7) bytes encode the content length.
    const lenLen = prefix - 0xb7;
    let len = 0;
    for (let i = 0; i < lenLen; i++) len = (len << 8) | buf[offset + 1 + i];
    return [offset + 1 + lenLen, len, 1 + lenLen + len];
  }
  if (prefix <= 0xf7) {
    // Short list: 0xc0..0xf7 — next (prefix - 0xc0) bytes are list payload.
    const len = prefix - 0xc0;
    return [offset + 1, len, 1 + len];
  }
  // Long list: 0xf8..0xff — next (prefix - 0xf7) bytes encode the payload length.
  const lenLen = prefix - 0xf7;
  let len = 0;
  for (let i = 0; i < lenLen; i++) len = (len << 8) | buf[offset + 1 + i];
  return [offset + 1 + lenLen, len, 1 + lenLen + len];
}

/** Decode a RLP big-integer item (short string encoding) as a BigInt. */
function rlpItemToBigInt(buf: Uint8Array, contentStart: number, contentLen: number): bigint {
  let v = 0n;
  for (let i = 0; i < contentLen; i++) {
    v = (v << 8n) | BigInt(buf[contentStart + i]);
  }
  return v;
}

/**
 * Recover the sender Ethereum address from a signed EIP-1559 transaction.
 *
 * Strategy:
 *  1. signingHash = keccak256(hexToBytes(unsignedTxHex))
 *     The unsigned EIP-1559 tx already IS the signing preimage:
 *       0x02 || rlp([chainId, nonce, maxPriorityFee, maxFee, gas, to, value, data, accessList])
 *     go-ethereum computes the signing hash as keccak256(type_byte || rlp_payload),
 *     which is exactly keccak256(all bytes of the unsigned tx).
 *
 *  2. Parse the signed tx to extract yParity, r, s.
 *     Signed EIP-1559 format: 0x02 || rlp([chainId, nonce, maxPriorityFee, maxFee,
 *       gas, to, value, data, accessList, yParity, r, s])  (12 items)
 *     We iterate the list items and capture the last 3.
 *
 *  3. Use secp256k1 signature recovery: recoverPublicKey(signingHash, sig, recovery).
 *
 *  4. Derive the Ethereum address from the recovered uncompressed public key.
 *
 * This is a TRUE cryptographic check: a signer that signed different fields than
 * requested would produce a wrong signing hash → wrong recovered address → test fails.
 */
function recoverSenderFromEIP1559Tx(
  signedTxHex: string,
  unsignedTxHex: string,
): string {
  // Step 1: compute the signing hash from the ORIGINAL unsigned tx bytes.
  const unsignedBytes = hexToBytes(unsignedTxHex.replace(/^0x/i, ""));
  const signingHash = keccak_256(unsignedBytes);

  // Step 2: parse r/s/yParity from the signed tx.
  const signedBytes = hexToBytes(signedTxHex.replace(/^0x/i, ""));
  // First byte is the EIP-2718 type byte (0x02); remainder is the RLP list.
  if (signedBytes[0] !== 0x02) {
    throw new Error(`Expected EIP-1559 type byte 0x02, got 0x${signedBytes[0].toString(16)}`);
  }
  const rlpPayload = signedBytes.slice(1);

  // Decode the top-level list.
  const [listContentStart, listContentLen] = rlpItemBounds(rlpPayload, 0);

  // Iterate all items in the list to find the last 3 (yParity, r, s).
  const items: Array<{ contentStart: number; contentLen: number }> = [];
  let pos = listContentStart;
  const listEnd = listContentStart + listContentLen;
  while (pos < listEnd) {
    const [cs, cl, total] = rlpItemBounds(rlpPayload, pos);
    items.push({ contentStart: cs, contentLen: cl });
    pos += total;
  }

  if (items.length < 3) {
    throw new Error(`Expected at least 3 RLP items in signed EIP-1559 tx list, got ${items.length}`);
  }

  const yParityItem = items[items.length - 3];
  const rItem = items[items.length - 2];
  const sItem = items[items.length - 1];

  const yParity = Number(rlpItemToBigInt(rlpPayload, yParityItem.contentStart, yParityItem.contentLen));
  const rBig = rlpItemToBigInt(rlpPayload, rItem.contentStart, rItem.contentLen);
  const sBig = rlpItemToBigInt(rlpPayload, sItem.contentStart, sItem.contentLen);

  if (yParity !== 0 && yParity !== 1) {
    throw new Error(`Unexpected yParity value ${yParity}`);
  }

  // Step 3: recover the public key.
  // addRecoveryBit attaches the yParity recovery bit to produce an ECDSASigRecovered,
  // then recoverPublicKey(msgHash) uses that recovery bit internally.
  const sig = new secp256k1.Signature(rBig, sBig).addRecoveryBit(yParity);
  const recoveredPoint = sig.recoverPublicKey(signingHash);
  const uncompressed = recoveredPoint.toRawBytes(false); // 65 bytes: 0x04 || x || y
  const pubBody = uncompressed.slice(1); // 64 bytes
  const addrHash = keccak_256(pubBody);
  return "0x" + bytesToHex(addrHash.slice(12)); // last 20 bytes
}

const BARE_64HEX_RE = /"([0-9a-f]{64})"/i;
function assertNoPlaintextKey(value: unknown): void {
  const str = JSON.stringify(value);
  const match = BARE_64HEX_RE.exec(str);
  if (match) {
    const forbidden = ["privateKeyHex", "rawPrivateKey", "privateKeyMaterial", "plaintext"];
    for (const f of forbidden) {
      if (str.includes(`"${f}"`)) {
        throw new Error(`Response contains forbidden plaintext field "${f}": ${str.slice(0, 300)}`);
      }
    }
  }
}

