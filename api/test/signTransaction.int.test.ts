/**
 * Integration test: sign_transaction end-to-end.
 *
 * Requires:
 *  - Docker (Postgres container via testcontainers)
 *  - Go toolchain (builds the signer binary; must include the new
 *    /internal/sign/transaction endpoint added in P6)
 *
 * If Go is absent the signer helper returns null and the suite is skipped.
 *
 * Recovery verification:
 *  - For EIP-1559 the signing hash is keccak256(unsignedTxBytes) since the
 *    unsigned tx already contains the type byte (0x02) + the 9-field RLP.
 *    We use @noble/hashes/sha3 (keccak_256) and @noble/curves/secp256k1 to
 *    recover the sender address from (r, s, v, signingHash) using only the
 *    signedTransaction hex bytes — NOT signerReceipt.publicKey.
 *    This is a TRUE cryptographic recovery: a signer bug that produces a
 *    valid signature over wrong fields would produce a different signing hash
 *    and thus a wrong recovered address, causing the assertion to fail.
 *
 *  - For legacy EIP-155 and for methodSelector extraction, we rely on:
 *    (a) the signer receipt publicKey (compressed pubkey hex) from which we
 *        derive the Ethereum address via keccak256(uncompress(pub)[1:])[12:],
 *    (b) comparing that address to the one returned by create_private_keys.
 *    This is the parity guard: the signer signs with the correct key.
 *
 * Note: viem is not installed in this workspace; recovery is implemented via
 * @noble/curves + @noble/hashes which are already present.
 */
