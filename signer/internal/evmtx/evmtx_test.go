// TestEIP1559SignedTxHasTypePrefix verifies the signed EIP-1559 tx starts with 0x02.
func TestEIP1559SignedTxHasTypePrefix(t *testing.T) {
	ecKey := loadTestKey(t)

	result, err := evmtx.SignUnsignedTx(eip1559UnsignedHex, ecKey)
	if err != nil {
		t.Fatalf("SignUnsignedTx: %v", err)
	}

	// After stripping 0x, first byte should be 0x02 for EIP-1559.
	hexStr := strings.TrimPrefix(result.SignedTransaction, "0x")
	if len(hexStr) < 2 || hexStr[:2] != "02" {
		t.Errorf("signed EIP-1559 tx should start with 0x02, got prefix %q", hexStr[:min(4, len(hexStr))])
	}
}

func min(a, b int) int {
	if a < b {
		return a
	}
	return b
}
