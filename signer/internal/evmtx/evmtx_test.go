// testKey is a well-known secp256k1 private key (Ganache account #0).
// Private key: 0x4f3edf983ac636a65a842ce7c78d9aa706d3b113bce9c46f30d7d21715b23b1d
// Expected address: 0x90F8bf6A479f320ead074411a4B0e7944Ea8c9C1
const (
	testPrivHex    = "4f3edf983ac636a65a842ce7c78d9aa706d3b113bce9c46f30d7d21715b23b1d"
	testKeyAddress = "0x90F8bf6A479f320ead074411a4B0e7944Ea8c9C1"
	sepoliaChainID = int64(11155111)
)

// Fixed unsigned EIP-1559 tx (type 0x02) for chainId=11155111 (Sepolia):
//
//	nonce=0, maxPriorityFeePerGas=1e9, maxFeePerGas=1e9, gas=21000,
//	to=0x000000000000000000000000000000000000dEaD, value=0, data=[], accessList=[]
//
// Generated by encoding the 9-field RLP list with 0x02 type prefix.
const eip1559UnsignedHex = "0x02ea83aa36a780843b9aca00843b9aca0082520894000000000000000000000000000000000000dead8080c0"

// Fixed unsigned legacy EIP-155 tx for chainId=11155111:
//
//	nonce=0, gasPrice=1e9, gas=21000, to=0x...dEaD, value=0, data=[]
//	9-field form: [nonce, gasPrice, gas, to, value, data, chainId, 0, 0]
const legacyUnsignedHex = "0xe680843b9aca0082520894000000000000000000000000000000000000dead808083aa36a78080"

// loadTestKey returns the Ganache account #0 ecdsa.PrivateKey.
func loadTestKey(t *testing.T) *ecdsa.PrivateKey {
	t.Helper()
	privBytes, err := hex.DecodeString(testPrivHex)
	if err != nil {
		t.Fatalf("decode test private key: %v", err)
	}
	ecKey, err := crypto.ToECDSA(privBytes)
	if err != nil {
		t.Fatalf("ToECDSA: %v", err)
	}
	return ecKey
}

// recoverSender decodes a signed tx hex and recovers the sender address.
func recoverSender(t *testing.T, signedTxHex string, chainID *big.Int) string {
	t.Helper()

	hexStr := signedTxHex
	if strings.HasPrefix(hexStr, "0x") || strings.HasPrefix(hexStr, "0X") {
		hexStr = hexStr[2:]
	}
	raw, err := hex.DecodeString(hexStr)
	if err != nil {
		t.Fatalf("decode signed tx hex: %v", err)
	}

	var tx types.Transaction
	if err := tx.UnmarshalBinary(raw); err != nil {
		t.Fatalf("UnmarshalBinary signed tx: %v", err)
	}

	signer := types.LatestSignerForChainID(chainID)
	addr, err := types.Sender(signer, &tx)
	if err != nil {
		t.Fatalf("types.Sender: %v", err)
	}
	return addr.Hex()
}

// TestEIP1559SignAndRecover signs a fixed EIP-1559 unsigned tx with a known key
// and verifies the signature recovers to the key's address.
func TestEIP1559SignAndRecover(t *testing.T) {
	ecKey := loadTestKey(t)

	result, err := evmtx.SignUnsignedTx(eip1559UnsignedHex, ecKey)
	if err != nil {
		t.Fatalf("SignUnsignedTx EIP-1559: %v", err)
	}

	if !strings.HasPrefix(result.SignedTransaction, "0x") {
		t.Errorf("SignedTransaction missing 0x prefix: %q", result.SignedTransaction)
	}

	// Verify the signed tx recovers to the key's address.
	chainID := big.NewInt(sepoliaChainID)
	recovered := recoverSender(t, result.SignedTransaction, chainID)
	if !strings.EqualFold(recovered, testKeyAddress) {
		t.Errorf("recovered sender = %q, want %q", recovered, testKeyAddress)
	}
}

// TestEIP1559FieldExtraction verifies that the extracted fields match the
// values encoded in the fixed test vector.
func TestEIP1559FieldExtraction(t *testing.T) {
	ecKey := loadTestKey(t)

	result, err := evmtx.SignUnsignedTx(eip1559UnsignedHex, ecKey)
	if err != nil {
		t.Fatalf("SignUnsignedTx EIP-1559: %v", err)
	}

	f := result.Fields

	// ChainID = 11155111 = 0xaa36a7
	if !strings.EqualFold(f.ChainID, "0xaa36a7") {
		t.Errorf("ChainID = %q, want 0xaa36a7", f.ChainID)
	}
	// To = 0x000...dEaD (checksummed)
	if !strings.EqualFold(f.To, "0x000000000000000000000000000000000000dEaD") {
		t.Errorf("To = %q, want 0x000...dEaD", f.To)
	}
	// Value = 0
	if !strings.EqualFold(f.Value, "0x0") {
		t.Errorf("Value = %q, want 0x0", f.Value)
	}
	// Nonce = 0
	if f.Nonce != 0 {
		t.Errorf("Nonce = %d, want 0", f.Nonce)
	}
	// Gas = 21000 = 0x5208
	if f.Gas != 21000 {
		t.Errorf("Gas = %d, want 21000", f.Gas)
	}
	// MaxFeePerGas = 1e9 = 0x3b9aca00
	if !strings.EqualFold(f.MaxFeePerGas, "0x3b9aca00") {
		t.Errorf("MaxFeePerGas = %q, want 0x3b9aca00", f.MaxFeePerGas)
	}
	// MaxPriorityFeePerGas = 1e9 = 0x3b9aca00
	if !strings.EqualFold(f.MaxPriorityFeePerGas, "0x3b9aca00") {
		t.Errorf("MaxPriorityFeePerGas = %q, want 0x3b9aca00", f.MaxPriorityFeePerGas)
	}
	// Data = empty → "0x"
	if f.Data != "0x" {
		t.Errorf("Data = %q, want 0x", f.Data)
	}
	// MethodSelector = "" (data < 4 bytes)
	if f.MethodSelector != "" {
		t.Errorf("MethodSelector = %q, want empty string", f.MethodSelector)
	}
	// GasPrice should be empty for EIP-1559
	if f.GasPrice != "" {
		t.Errorf("GasPrice = %q, want empty for EIP-1559", f.GasPrice)
	}
}

