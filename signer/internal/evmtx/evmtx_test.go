// TestMethodSelectorExtraction verifies the first 4 bytes of calldata are extracted correctly.
func TestMethodSelectorExtraction(t *testing.T) {
	// Build an EIP-1559 unsigned tx with calldata starting 0x7fea8778 (sweep-like selector).
	ecKey := loadTestKey(t)

	// We construct a custom unsigned tx with 4+ bytes of calldata.
	// Use the helper to build raw bytes.
	chainID := big.NewInt(sepoliaChainID)

	// Build the 9-field list manually using types package for correctness.
	to := common.HexToAddress("0x000000000000000000000000000000000000dEaD")
	calldata := []byte{0x7f, 0xea, 0x87, 0x78, 0xab, 0xcd, 0xef, 0x01, 0x02, 0x03}

	inner := struct {
		ChainID              *big.Int
		Nonce                uint64
		MaxPriorityFeePerGas *big.Int
		MaxFeePerGas         *big.Int
		Gas                  uint64
		To                   []byte
		Value                *big.Int
		Data                 []byte
		AccessList           types.AccessList
	}{
		ChainID:              chainID,
		Nonce:                1,
		MaxPriorityFeePerGas: big.NewInt(1_000_000_000),
		MaxFeePerGas:         big.NewInt(1_000_000_000),
		Gas:                  100_000,
		To:                   to.Bytes(),
		Value:                big.NewInt(0),
		Data:                 calldata,
		AccessList:           types.AccessList{},
	}

	encoded, err := rlp.EncodeToBytes(inner)
	if err != nil {
		t.Fatalf("rlp.EncodeToBytes: %v", err)
	}
	txBytes := append([]byte{0x02}, encoded...)
	txHex := "0x" + hex.EncodeToString(txBytes)

	result, err := evmtx.SignUnsignedTx(txHex, ecKey)
	if err != nil {
		t.Fatalf("SignUnsignedTx with calldata: %v", err)
	}

	if result.Fields.MethodSelector != "0x7fea8778" {
		t.Errorf("MethodSelector = %q, want 0x7fea8778", result.Fields.MethodSelector)
	}

	// Data should start with the full calldata.
	if !strings.HasPrefix(result.Fields.Data, "0x7fea8778") {
		t.Errorf("Data = %q, want 0x7fea8778... prefix", result.Fields.Data)
	}

	// Recovery must still work.
	recovered := recoverSender(t, result.SignedTransaction, chainID)
	if !strings.EqualFold(recovered, testKeyAddress) {
		t.Errorf("recovered sender with calldata = %q, want %q", recovered, testKeyAddress)
	}
}

